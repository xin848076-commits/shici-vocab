const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ctx = { console, window: {}, document: { getElementById: () => null } };
ctx.globalThis = ctx;
vm.createContext(ctx);
for (const file of ['vocab-spell/typo-js/typo.js', 'vocab-spell/dictionaries.js']) vm.runInContext(fs.readFileSync(file, 'utf8'), ctx);
ctx.SHICI_DICTIONARIES = ctx.window.SHICI_DICTIONARIES;
vm.runInContext(fs.readFileSync('vocab-spell.js', 'utf8'), ctx);
console.time('dictionary init');
ctx.ShiciSpelling.init();
console.timeEnd('dictionary init');
for (const word of ['endeavor', 'endeavour', 'systematically', 'hello', 'colour', 'color', 'be obsessed with', 'brand-name products', "don't", 'don’t', 'in-person', 'as is vividly depicted in ...']) assert.equal(ctx.ShiciSpelling.inspect(word).length, 0, word);
for (const word of ['endeaver', 'recieve', 'benificial', 'helo']) assert.equal(ctx.ShiciSpelling.inspect(word).length, 1, word);
const phrase = 'be obssesed with';
const [error] = ctx.ShiciSpelling.inspect(phrase);
assert.equal(error.word, 'obssesed');
assert.equal(phrase.slice(error.start, error.end), 'obssesed');
assert.equal(ctx.ShiciSpelling.inspect('（观点）... for the following reasons').length, 0);
assert.equal(ctx.ShiciSpelling.inspect('').length, 0);
console.time('suggest');
assert.ok(ctx.ShiciSpelling.suggest('endeaver').includes('endeavor'));
console.timeEnd('suggest');
const backup = JSON.parse(fs.readFileSync('拾词备份-2026-11-08-1794125998922.json', 'utf8'));
console.log('Unrecognized tokens in original backup:', backup.words.flatMap(entry => ctx.ShiciSpelling.inspect(entry.word).map(token => token.word)));
console.log('Offline engine checks passed.');
